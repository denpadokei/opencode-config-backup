<#
.SYNOPSIS
    Restores the OpenCode / OpenChamber configuration from this repository.

.DESCRIPTION
    Copies the backed-up files back into the live config folders, leaving
    anything secret (service.json, relay-identity.json,
    git-credential-endpoint.json) untouched: those are regenerated by the
    apps themselves. Run this before starting OpenCode / OpenChamber after a
    reinstall.

    This is the mechanical half of RESTORE.md — the AI-facing procedure with
    prerequisites, secrets and verification lives there.

.EXAMPLE
    .\restore.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$OpenCode = Join-Path $env:USERPROFILE '.config\opencode'
$OpenChamber = Join-Path $env:USERPROFILE '.config\openchamber'
New-Item -ItemType Directory -Force -Path $OpenCode, $OpenChamber | Out-Null

# Source (inside this repo)  ->  live destination. Folder sources are copied
# recursively and merged.
$Items = @(
    @{ Src = 'opencode\opencode.jsonc';            Dst = Join-Path $OpenCode 'opencode.jsonc' },
    @{ Src = 'opencode\dcp.jsonc';                 Dst = Join-Path $OpenCode 'dcp.jsonc' },
    @{ Src = 'opencode\cli.json';                  Dst = Join-Path $OpenCode 'cli.json' },
    @{ Src = 'opencode\oh-my-opencode-slim.json';  Dst = Join-Path $OpenCode 'oh-my-opencode-slim.json' },
    @{ Src = 'opencode\skills';                    Dst = Join-Path $OpenCode 'skills' },
    @{ Src = 'openchamber\preferences.json';       Dst = Join-Path $OpenChamber 'preferences.json' },
    @{ Src = 'openchamber\routing.json';           Dst = Join-Path $OpenChamber 'routing.json' },
    @{ Src = 'openchamber\settings.local.json';    Dst = Join-Path $OpenChamber 'settings.json' }
)

foreach ($item in $Items) {
    $src = Join-Path $PSScriptRoot $item.Src
    if (-not (Test-Path $src)) {
        Write-Warning "not present in this repo, skipped: $($item.Src)"
        continue
    }
    if (Test-Path $src -PathType Container) {
        Copy-Item (Join-Path $src '*') $item.Dst -Recurse -Force
        Write-Host "restored dir   $($item.Src) -> $($item.Dst)"
    }
    else {
        Copy-Item $src $item.Dst -Force
        Write-Host "restored file  $($item.Src) -> $($item.Dst)"
    }
}

Write-Host ""
Write-Host "Config files restored. Secrets were NOT touched:"
Write-Host "  ~/.config/opencode/service.json            (regenerated on first run)"
Write-Host "  ~/.config/openchamber/relay-identity.json  (regenerated by OpenChamber)"
Write-Host "  ~/.config/openchamber/git-credential-endpoint.json (regenerated by OpenChamber)"
Write-Host ""
Write-Host "Next steps for a fresh machine are in RESTORE.md."